package kr.ivlis.ivlyricsandroid;

import org.json.JSONArray;
import org.json.JSONObject;

/** Frozen at the user's Share click, before any authentication or network work. */
final class VideoTimingSubmission {
    final String isrc, trackId, title, artist, album, videoId, videoTitle;
    final double startTime;

    private VideoTimingSubmission(TrackSnapshot track, String isrc, String trackId,
            YouTubeBackgroundRepository.VideoInfo video, double startTime) {
        this.isrc = isrc;
        this.trackId = trackId;
        this.title = track.title;
        this.artist = track.artist;
        this.album = track.album;
        this.videoId = video.youtubeVideoId;
        this.videoTitle = video.youtubeTitle;
        this.startTime = startTime;
    }

    static VideoTimingSubmission capture(TrackSnapshot track, String isrc, String trackId,
            YouTubeBackgroundRepository.VideoInfo applied, long firstLyricMs, int videoOffsetMs) {
        String normalizedIsrc = TrackSnapshot.normalizeIsrc(isrc);
        if (track == null || !track.hasUsableMetadata() || applied == null || applied.autoGenerated
                || normalizedIsrc.isEmpty() || trackId == null || !trackId.matches("[A-Za-z0-9]{22}")
                || applied.youtubeVideoId.isEmpty() || firstLyricMs < 0
                || (!applied.spotifyTrackId.isEmpty() && !trackId.equals(applied.spotifyTrackId))) return null;
        // Match native playback's caption anchor. Device/global/lyric offsets are personal and are not shared.
        double start = (applied.hasCaptionStartTime ? applied.captionStartTimeSeconds : firstLyricMs / 1000d)
                + videoOffsetMs / 1000d;
        if (!Double.isFinite(start) || start < 0d || start > 3600d) return null;
        return new VideoTimingSubmission(track, normalizedIsrc, trackId, applied, start);
    }

    JSONObject toJson() throws Exception {
        return new JSONObject().put("action", "submit").put("isrc", isrc).put("trackId", trackId)
                .put("title", title).put("artist", artist).put("album", album)
                .put("videoId", videoId).put("videoTitle", videoTitle).put("startTime", startTime)
                .put("skipSegments", new JSONArray());
    }
}
