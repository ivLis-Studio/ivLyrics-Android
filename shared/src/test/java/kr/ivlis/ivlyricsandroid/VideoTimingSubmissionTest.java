package kr.ivlis.ivlyricsandroid;

import org.junit.Test;
import static org.junit.Assert.*;

public final class VideoTimingSubmissionTest {
    private static final String TRACK = "1234567890123456789012";
    private static final String ISRC = "USAAA2600001";

    private TrackSnapshot track() {
        return new TrackSnapshot("Song", "Artist", "Album", "com.spotify.music", "spotify:track:" + TRACK,
                ISRC, 120000, 10000, 1, 1f, false, null, "");
    }

    private YouTubeBackgroundRepository.VideoInfo video(String id, boolean caption, double start, boolean auto) {
        return new YouTubeBackgroundRepository.VideoInfo(ISRC, TRACK, id, "Video", caption, start, auto, "");
    }

    @Test public void capturesAppliedIdAndExactFractionalCaptionPlusVideoOffset() {
        var applied = video("Abc_123-XyZ", true, 12.345, false);
        var captured = VideoTimingSubmission.capture(track(), ISRC, TRACK, applied, 3000, -125);
        assertNotNull(captured);
        assertEquals("Abc_123-XyZ", captured.videoId);
        assertEquals(12.220, captured.startTime, 0.0000001);
        var replacement = VideoTimingSubmission.capture(track(), ISRC, TRACK,
                video("Zyx_987-WvU", true, 99, false), 3000, 100);
        assertEquals("Zyx_987-WvU", replacement.videoId);
        assertEquals("Abc_123-XyZ", captured.videoId);
        assertEquals(12.220, captured.startTime, 0.0000001);
    }

    @Test public void aVideoWithoutCaptionUsesTheNativeFirstLyricAnchor() {
        var captured = VideoTimingSubmission.capture(track(), ISRC, TRACK,
                video("Abc_123-XyZ", false, 0, false), 4230, 10);
        assertNotNull(captured);
        assertEquals(4.240, captured.startTime, 0.0000001);
    }

    @Test public void rejectsMissingIdentityAutoVideosAndInvalidTiming() {
        var applied = video("Abc_123-XyZ", true, 1, false);
        assertNull(VideoTimingSubmission.capture(null, ISRC, TRACK, applied, 0, 0));
        assertNull(VideoTimingSubmission.capture(track(), "", TRACK, applied, 0, 0));
        assertNull(VideoTimingSubmission.capture(track(), ISRC, "wrong", applied, 0, 0));
        assertNull(VideoTimingSubmission.capture(track(), ISRC, TRACK, null, 0, 0));
        assertNull(VideoTimingSubmission.capture(track(), ISRC, TRACK, applied, -1, 0));
        assertNull(VideoTimingSubmission.capture(track(), ISRC, TRACK, applied, 0, -1001));
        assertNull(VideoTimingSubmission.capture(track(), ISRC, TRACK, video("invalid", true, 1, false), 0, 0));
        assertNull(VideoTimingSubmission.capture(track(), ISRC, TRACK, video("Abc_123-XyZ", true, 1, true), 0, 0));
        var wrongTrack = new YouTubeBackgroundRepository.VideoInfo(ISRC, "abcdefghijklmnopqrstuv",
                "Abc_123-XyZ", "Other track", true, 1, false, "");
        assertNull(VideoTimingSubmission.capture(track(), ISRC, TRACK, wrongTrack, 0, 0));
    }

    @Test public void preservesZeroAndRejectsOutOfRangeRatherThanClamping() {
        assertEquals(0d, VideoTimingSubmission.capture(track(), ISRC, TRACK,
                video("Abc_123-XyZ", true, 0, false), 0, 0).startTime, 0);
        assertEquals(3600d, VideoTimingSubmission.capture(track(), ISRC, TRACK,
                video("Abc_123-XyZ", true, 3600, false), 0, 0).startTime, 0);
        assertNull(VideoTimingSubmission.capture(track(), ISRC, TRACK,
                video("Abc_123-XyZ", true, 3600, false), 0, 1));
    }

    @Test public void manuallyCorrectedAutomaticZeroKeepsPlaybackAndBecomesShareable() {
        var automatic = video("Abc_123-XyZ", true, 0, true);
        assertNull(VideoTimingSubmission.capture(track(), ISRC, TRACK, automatic, 5230, 125));
        var edited = automatic.withManualTiming(5230);
        assertNotNull(edited);
        assertFalse(edited.autoGenerated);
        assertEquals(automatic.youtubeVideoId, edited.youtubeVideoId);
        assertEquals(5.230, edited.captionStartTimeSeconds, 0.0000001);
        double beforeEditVideoPosition = 42d + 0.125d; // Automatic zero uses the song's time directly.
        double afterEditVideoPosition = 42d + edited.captionStartTimeSeconds - 5.230d + 0.125d;
        assertEquals(beforeEditVideoPosition, afterEditVideoPosition, 0.0000001);
        var share = VideoTimingSubmission.capture(track(), ISRC, TRACK, edited, 5230, 125);
        assertNotNull(share);
        assertEquals(5.355, share.startTime, 0.0000001);
        assertNull(automatic.withManualTiming(-1));
        var known = video("Abc_123-XyZ", true, 12.345, true).withManualTiming(5230);
        assertEquals(12.345, known.captionStartTimeSeconds, 0.0000001);
    }

    @Test public void sharingStringsHaveExplicitTranslationsInAll22Languages() {
        for (AiLyricsSettings.Language language : AppI18n.UI_LANGUAGES) {
            java.util.Map<String, String> translated = new java.util.HashMap<>();
            VideoSelectionTranslations.apply(language.code, translated);
            for (String key : new String[]{"video.share_timing", "video.timing_shared",
                    "video.share_timing_failed", "video.cannot_share_timing"}) {
                String value = translated.get(key);
                assertNotNull(language.code + ":" + key, value);
                assertFalse(value.isBlank());
                assertEquals(value, AppI18n.t(language.code, key));
                if (!"en".equals(language.code)) assertNotEquals(AppI18n.t("en", key), value);
            }
        }
    }
}
