    private static void put(Map<String, Map<String, String>> languages, String code, String[] values) {
        Map<String, String> current = languages.get(code);
        if (current == null) return;
        Map<String, String> copy = new LinkedHashMap<>(current);
        for (int index = 0; index + 1 < values.length; index += 2) copy.put(values[index], values[index + 1]);
        copy.put("tmi.loading_provider_format", copy.get("tmi.loading") + " · %s");
        String vinylHint = copy.get("vinyl.tmi_hint");
        if (vinylHint != null) {
            if ("pt".equals(code)) copy.put("vinyl.tmi_hint", vinylHint.replace("o TMI", "a Pesquisa"));
            else if ("tr".equals(code)) copy.put("vinyl.tmi_hint", vinylHint.replace("TMI'ı", "Araştırma'yı"));
            else copy.put("vinyl.tmi_hint", vinylHint.replace("TMI", copy.get("tmi.title")));
        }
        languages.put(code, Collections.unmodifiableMap(copy));
    }
